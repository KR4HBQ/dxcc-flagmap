#!/usr/bin/env python3
"""Generate examples/sample.adi: a synthetic log (NOT a real one) for demos and tests.

Run from the repo root:  python examples/make_sample.py
"""
import json
import random
from pathlib import Path

random.seed(250)
root = Path(__file__).resolve().parents[1]
ents = json.loads((root / "src/dxcc_flagmap/data/dxcc_entities.json").read_text())
# a few heavy hitters so the grid looks like a real DX log
heavy = {291: 40, 230: 40, 248: 40, 223: 40, 54: 40, 339: 40, 281: 40, 227: 40, 1: 40,
         263: 40, 269: 27, 150: 23, 108: 23, 209: 23, 120: 16}
lines = ["Synthetic sample log generated by examples/make_sample.py (not a real log)",
         "<adif_ver:5>3.1.4", "<programid:7>example", "<eoh>"]


def field(k, v):
    return f"<{k}:{len(str(v))}>{v}"


for e in ents:
    n = heavy.get(e["dxcc"], random.choice([1, 1, 1, 2, 2, 3, 4, 5]) if random.random() < 0.55 else 0)
    for _ in range(n):
        rec = (field("call", f"{e['prefix'] or 'X'}{random.randint(1, 9)}ABC")
               + field("qso_date", f"2026{random.randint(1, 9):02d}{random.randint(1, 28):02d}")
               + field("band", "20m") + field("mode", "FT8")
               + field("dxcc", e["dxcc"]) + field("country", e["name"]))
        if random.random() < 0.6:
            rec += field("lotw_qsl_rcvd", "Y")
        lines.append(rec + "<eor>")
(root / "examples" / "sample.adi").write_text("\n".join(lines) + "\n")
